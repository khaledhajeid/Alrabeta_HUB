const TRACK_ICONS = {
  git: GitIcon,
  bash: TerminalIcon,
  docker: BoxIcon,
  systems: CpuIcon,
} as const;

export type TrackIconName = keyof typeof TRACK_ICONS;

export function TrackIcon({ icon, ...props }: { icon: string } & React.SVGProps<SVGSVGElement>) {
  const Icon = TRACK_ICONS[icon as TrackIconName] ?? CpuIcon;
  return <Icon {...props} />;
}
